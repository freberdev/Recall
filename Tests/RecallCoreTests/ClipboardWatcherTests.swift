import Foundation
import Testing
@testable import RecallCore

@Suite struct CaptureRuleTests {
    @Test func plainTextMayBeRead() {
        #expect(CaptureRule.allowsReading(types: ["public.utf8-plain-text"]))
        #expect(CaptureRule.allowsReading(types: ["public.html", "public.utf8-plain-text", "public.rtf"]))
    }

    @Test func aClipboardWithoutPlainTextIsLeftAlone() {
        #expect(!CaptureRule.allowsReading(types: []))
        #expect(!CaptureRule.allowsReading(types: ["public.tiff", "public.png"]))
    }

    @Test(arguments: [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ])
    func whatAnAppMarksAsConfidentialIsLeftAlone(_ marker: String) {
        #expect(!CaptureRule.allowsReading(types: ["public.utf8-plain-text", marker]))
    }

    @Test func filesAreLeftAlone() {
        #expect(!CaptureRule.allowsReading(types: ["public.file-url", "public.utf8-plain-text"]))
    }

    @Test func textStillOnAnotherDeviceIsLeftAlone() {
        #expect(!CaptureRule.allowsReading(types: ["public.utf8-plain-text", "com.apple.is-remote-clipboard"]))
    }

    @Test func textIsKeptExactlyAsCopied() {
        #expect(CaptureRule.text(from: "  padded \n") == "  padded \n")
    }

    @Test func emptyAndBlankTextIsNotKept() {
        #expect(CaptureRule.text(from: nil) == nil)
        #expect(CaptureRule.text(from: "") == nil)
        #expect(CaptureRule.text(from: " \n\t ") == nil)
    }

    @Test func textAboveTheSizeLimitIsNotKept() {
        let atLimit = String(repeating: "a", count: CaptureRule.maxBytes)
        #expect(CaptureRule.text(from: atLimit) != nil)
        #expect(CaptureRule.text(from: atLimit + "a") == nil)
        // The limit is in bytes: "å" is two.
        #expect(CaptureRule.text(from: String(repeating: "å", count: CaptureRule.maxBytes / 2 + 1)) == nil)
    }
}

@MainActor @Suite struct ClipboardWatcherTests {
    let temp = TempDirectory()
    let clipboard = FakeClipboard()
    let store: HistoryStore
    let watcher: ClipboardWatcher

    init() {
        store = HistoryStore(files: temp.files(), limits: Limits(maxCount: 100, maxAgeDays: nil))
        watcher = ClipboardWatcher(source: clipboard, store: store, now: { date(1) })
    }

    @Test func aCopyIsRecordedOnce() {
        watcher.start()
        clipboard.copy("hello")
        watcher.poll()
        #expect(store.clips.map(\.text) == ["hello"])
    }

    @Test func repeatedPollsOfAnUnchangedClipboardAddNothingAndReadNothing() {
        watcher.start()
        clipboard.copy("hello")
        for _ in 0..<50 { watcher.poll() }

        #expect(store.clips.count == 1)
        #expect(clipboard.reads == 1)
        #expect(temp.fileNames().count == 1)
    }

    @Test func whatWasOnTheClipboardBeforeStartIsNotCollected() {
        clipboard.copy("copied before Recall was running")
        watcher.start()
        watcher.poll()
        #expect(store.clips.isEmpty)
        #expect(clipboard.reads == 0)
    }

    @Test func severalCopiesAreRecordedNewestFirst() {
        watcher.start()
        for text in ["a snippet", "https://example.com", "an address"] {
            clipboard.copy(text)
            watcher.poll()
        }
        #expect(store.clips.map(\.text) == ["an address", "https://example.com", "a snippet"])
        #expect(store.clips.map(\.kind) == [.text, .link, .text])
    }

    @Test func copyingTheSameTextTwiceGivesOneClip() {
        watcher.start()
        clipboard.copy("same")
        watcher.poll()
        clipboard.copy("same")
        watcher.poll()
        #expect(store.clips.count == 1)
    }

    @Test func confidentialContentIsNeverRead() {
        watcher.start()
        clipboard.copy("hunter2", extraTypes: ["org.nspasteboard.ConcealedType"])
        watcher.poll()
        #expect(store.clips.isEmpty)
        #expect(clipboard.reads == 0)
    }

    @Test func aConfidentialCopyIsNotPickedUpOnALaterPollEither() {
        watcher.start()
        clipboard.copy("hunter2", extraTypes: ["org.nspasteboard.ConcealedType"])
        watcher.poll()
        clipboard.types = [CaptureRule.plainText] // the marker disappears without a new copy
        watcher.poll()
        #expect(store.clips.isEmpty)
    }

    @Test func whileTheClipboardCannotBeReadNothingIsRecorded() {
        watcher.start()
        clipboard.copy("hidden")
        clipboard.string = nil
        watcher.poll()
        #expect(store.clips.isEmpty)
    }

    // MARK: Changes during a read

    @Test func aClipboardThatIsReplacedWhileItIsReadIsNotRecorded() {
        watcher.start()
        clipboard.copy("ordinary text")
        clipboard.onRead = { [clipboard] in
            clipboard.onRead = nil
            clipboard.copy("hunter2", extraTypes: ["org.nspasteboard.ConcealedType"])
        }
        watcher.poll()
        #expect(store.clips.isEmpty)

        // The replacement is then judged on its own, and it is confidential.
        watcher.poll()
        #expect(store.clips.isEmpty)
        #expect(clipboard.reads == 1)
    }

    @Test func aReplacementThatMayBeKeptIsRecordedOnTheNextPoll() {
        watcher.start()
        clipboard.copy("first")
        clipboard.onRead = { [clipboard] in
            clipboard.onRead = nil
            clipboard.copy("second")
        }
        watcher.poll()
        #expect(store.clips.isEmpty)
        watcher.poll()
        #expect(store.clips.map(\.text) == ["second"])
    }

    @Test func aConfidentialMarkerAddedDuringTheReadIsHonoured() {
        watcher.start()
        clipboard.copy("hunter2")
        clipboard.onRead = { [clipboard] in
            clipboard.types.append("org.nspasteboard.ConcealedType")
        }
        watcher.poll()
        #expect(store.clips.isEmpty)
    }

    // MARK: Pausing

    @Test func nothingIsReadOrRecordedWhilePaused() {
        watcher.start()
        watcher.isPaused = true
        clipboard.copy("copied while paused")
        watcher.poll()
        #expect(store.clips.isEmpty)
        #expect(clipboard.reads == 0)
    }

    @Test func whatWasCopiedWhilePausedIsNotCollectedOnResume() {
        watcher.start()
        watcher.isPaused = true
        clipboard.copy("copied while paused")
        watcher.poll()
        watcher.isPaused = false
        watcher.poll()
        #expect(store.clips.isEmpty)

        clipboard.copy("copied after resuming")
        watcher.poll()
        #expect(store.clips.map(\.text) == ["copied after resuming"])
    }

    @Test func whatWasCopiedJustBeforeResumingIsNotCollected() {
        watcher.start()
        watcher.isPaused = true
        // No poll gets in between the copy and the resume.
        clipboard.copy("copied a moment before resuming")
        watcher.isPaused = false
        watcher.poll()
        #expect(store.clips.isEmpty)
        #expect(clipboard.reads == 0)
    }

    @Test func whatWasCopiedJustBeforePausingIsNotCollected() {
        watcher.start()
        clipboard.copy("copied a moment before pausing")
        watcher.isPaused = true
        watcher.poll()
        watcher.isPaused = false
        watcher.poll()
        #expect(store.clips.isEmpty)
        #expect(clipboard.reads == 0)
    }

    @Test func aWatcherCanStartPaused() {
        let paused = ClipboardWatcher(source: clipboard, store: store, isPaused: true, now: { date(1) })
        paused.start()
        clipboard.copy("nope")
        paused.poll()
        #expect(store.clips.isEmpty)
    }

    // MARK: Recall's own writes

    @Test func aChangeMadeByRecallItselfIsNotRecordedAgain() {
        watcher.start()
        clipboard.copy("old")
        watcher.poll()
        clipboard.copy("new")
        watcher.poll()

        // Recall puts "old" back on the clipboard and tells the watcher.
        clipboard.copy("old")
        watcher.ignoreChange(clipboard.changeCount)
        let readsBefore = clipboard.reads
        watcher.poll()

        #expect(clipboard.reads == readsBefore)
        #expect(store.clips.map(\.text) == ["new", "old"])
    }

    @Test func theNextRealCopyAfterRecallsOwnWriteIsRecorded() {
        watcher.start()
        clipboard.copy("restored")
        watcher.ignoreChange(clipboard.changeCount)
        watcher.poll()
        clipboard.copy("fresh")
        watcher.poll()
        #expect(store.clips.map(\.text) == ["fresh"])
    }

    @Test func aPollBeforeStartRecordsTheFirstChangeItSees() {
        clipboard.copy("first")
        watcher.poll()
        #expect(store.clips.map(\.text) == ["first"])
    }
}

/// A clipboard the tests control.
@MainActor
final class FakeClipboard: ClipboardSource {
    var changeCount = 0
    var types: [String] = []
    var string: String?
    /// How many times the content has been read.
    private(set) var reads = 0

    /// Called in the middle of a read, to stand in for another app changing the clipboard.
    var onRead: (() -> Void)?

    func readString() -> String? {
        reads += 1
        let string = string
        onRead?()
        return string
    }

    func copy(_ text: String, extraTypes: [String] = []) {
        changeCount += 1
        string = text
        types = [CaptureRule.plainText] + extraTypes
    }
}
