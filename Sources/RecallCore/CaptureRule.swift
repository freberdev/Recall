/// Decides what on the clipboard goes into the history.
///
/// The decision is made in two steps. The first looks only at which kinds of data the clipboard
/// says it holds, so that a password is never read at all. The second looks at the text.
public enum CaptureRule {
    /// Larger texts than this are left out of the history.
    public static let maxBytes = 1_000_000

    public static let plainText = "public.utf8-plain-text"

    /// Markers that apps put on the clipboard to say "do not keep this".
    /// See nspasteboard.org for the convention password managers follow.
    static let confidential: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        // Older markers from before the convention, still in use.
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Kinds of content Recall does not collect: files, and text that is still on another
    /// device and would have to be fetched from it.
    static let unsupported: Set<String> = [
        "public.file-url",
        "com.apple.is-remote-clipboard",
    ]

    /// The image formats Recall reads, the one it would rather have first.
    public static let imageTypes = ["public.png", "public.jpeg", "public.tiff", "public.heic"]

    /// Formatted text. An office app puts it beside copied text, together with a picture of
    /// the selection, while a browser that copies an image does not.
    static let richText: Set<String> = ["public.rtf", "com.apple.flat-rtfd", "com.apple.rtfd"]

    /// What the clipboard offers that Recall may collect.
    public enum Content: Equatable, Sendable {
        case nothing
        case text
        case image
        /// Both. Which one to keep is decided by `prefersImage(over:)` once the text is read.
        case textAndImage
    }

    /// Judged from the kinds of data alone, without reading any of it.
    public static func content(types: [String], collectsImages: Bool) -> Content {
        guard confidential.isDisjoint(with: types), unsupported.isDisjoint(with: types) else { return .nothing }
        let hasText = types.contains(plainText)
        let hasImage = collectsImages && types.contains(where: imageTypes.contains)
        switch (hasText, hasImage) {
        case (true, true): return richText.isDisjoint(with: types) ? .textAndImage : .text
        case (true, false): return .text
        case (false, true): return .image
        case (false, false): return .nothing
        }
    }

    /// True when the clipboard holds plain text and nothing says to leave it alone.
    public static func allowsReading(types: [String]) -> Bool {
        let content = content(types: types, collectsImages: false)
        return content == .text
    }

    /// When the clipboard holds both text and an image, which one did the user copy?
    ///
    /// A browser puts the address next to a copied image, and then the image is the point.
    /// An app that puts a picture of the selection next to copied text means the text. So the
    /// image wins only over a lone address, or no text. Text that comes with formatting never
    /// gets this far: `content(types:collectsImages:)` has already called it text.
    public static func prefersImage(over string: String?) -> Bool {
        guard let text = text(from: string) else { return true }
        return Clip.Kind.of(text) == .link
    }

    /// The text to keep, exactly as copied, or nil if it is empty, only whitespace or too large.
    public static func text(from string: String?) -> String? {
        guard let string, string.utf8.count <= maxBytes,
              string.contains(where: { !$0.isWhitespace })
        else { return nil }
        return string
    }
}
